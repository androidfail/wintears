#!/usr/bin/env python3
"""Generate guest-to-host bridge thunks from upstream's NVN implementations.

On the Mac, the game calls the host's NVN functions directly: both are ARM64 with the same calling convention. On
x86-64 the game runs in the JIT, so each host function gets a thunk that reads its arguments from the guest registers
(AAPCS64: integers and pointers in x0..x7, floats in v0..v7, the rest in 8-byte stack slots), calls the function
with the Windows x64 convention, and writes the result back (x0, v0, or the x8 result buffer for large structs).

The signatures come from the NVN(name, ret, params...) definitions in upstream's sources, which are the host
implementations' exact types.

Usage: python3 tools/gen_bridge.py <out.c> <source files...> [--include header.h] [--table name]
"""
import re
import sys
from pathlib import Path

MACROS = ('NVN', 'NVN_NOPROTO', 'NVN_EXTRA')
FLOATS = {'float': 's', 'double': 'd'}


def split_top(text, sep=','):
    """Split at top-level separators (not inside parentheses or brackets)."""
    out, depth, cur = [], 0, []
    for ch in text:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(''.join(cur))
            cur = []
        else:
            cur.append(ch)
    out.append(''.join(cur))
    return [s.strip() for s in out]


def definitions(source):
    """Yield (macro, name, ret, params text) for each NVN(...) definition in a C source."""
    for m in re.finditer(r'^\s*(%s)\(' % '|'.join(MACROS), source, re.M):
        i, depth = m.end(), 1
        while depth:
            depth += {'(': 1, ')': -1}.get(source[i], 0)
            i += 1
        parts = split_top(source[m.end():i - 1])
        if len(parts) < 2:
            continue
        name, ret = parts[0], parts[1]
        yield m.group(1), name, ret, parts[2:]


def param_type(p):
    """'const NVNdevice *d' -> 'const NVNdevice *'; 'void (*cb)(int)' -> 'void *'; 'float c[4]' -> 'float *'."""
    p = ' '.join(p.split())
    if '(*' in p:
        return 'void *'
    p = re.sub(r'\[[^\]]*\]$', '', p).strip() + (' *' if p.endswith(']') else '')
    m = re.match(r'^(.*?)([A-Za-z_]\w*)\s*(\*?)$', p)
    if m and m.group(1).strip() and not m.group(1).strip().endswith(('struct', 'enum', 'unsigned', 'signed')):
        return (m.group(1) + m.group(3)).strip()
    return p


def base_type(t):
    return ' '.join(w for w in t.replace('*', ' * ').split() if w not in ('const', 'volatile'))


def thunk(name, ret, params, prefix):
    if any(p == '...' for p in params):
        raise ValueError(f'{name}: variadic host functions need a hand-written thunk')
    types = [param_type(p) for p in params if p and p != 'void']
    decl, args = [], []
    for i, t in enumerate(types):
        bt = base_type(t)
        if '*' in t:
            # every pointer is 8 bytes in one register: void * keeps private pointee types out of this file
            decl.append(f'    void *a{i}; take_gp(c, &g, &s, &a{i}, 8);')
            args.append(f'a{i}')
        elif bt in FLOATS:
            decl.append(f'    {bt} a{i}; take_fp(c, &f, &s, &a{i}, sizeof a{i});')
            args.append(f'a{i}')
        else:
            # integers, enums and small structs (<= 16 bytes: one or two registers, AAPCS64)
            decl.append(f'    {bt} a{i}; take_gp(c, &g, &s, &a{i}, sizeof a{i});')
            args.append(f'a{i}')
    ptypes = ['void *' if '*' in t else base_type(t) for t in types]
    proto = ', '.join(ptypes) or 'void'
    rb = base_type(ret)
    rt = 'void *' if '*' in ret else ret
    call = f'(({rt} (*)({proto}))fn)({", ".join(args)})'
    head = ['    unsigned g = 0, f = 0, s = 0;', '    (void)g; (void)f; (void)s;']
    if rb == 'void' and '*' not in ret:
        body = [f'    {call};']
    elif rb in FLOATS and '*' not in ret:
        body = [f'    {rb} r = {call};', '    put_fp(c, &r, sizeof r);']
    else:
        body = [f'    {rt} r = {call};', '    put_gp(c, &r, sizeof r);']
    return f'static void {prefix}{name}(jit_context *c, void *fn) {{\n' + '\n'.join(head + decl + body) + '\n}\n'


HEADER = '''/* Generated by tools/gen_bridge.py. Do not edit. */
#include <stdint.h>
#include <string.h>
#include "bridge/bridge.h"
#include "%(include)s"

/* AAPCS64 argument passing (sizes are compile-time constants, so these fold away). */
static inline const void *stack_slot(const jit_context *c, unsigned s) { return (const void *)(uintptr_t)(c->sp + 8u * s); }
static inline void take_gp(const jit_context *c, unsigned *g, unsigned *s, void *dst, size_t size) {
    unsigned n = (unsigned)((size + 7) / 8);
    if (*g + n <= 8) { memcpy(dst, &c->x[*g], size); *g += n; }
    else { *g = 8; memcpy(dst, stack_slot(c, *s), size); *s += n; }   /* no splitting between registers and stack */
}
static inline void take_fp(const jit_context *c, unsigned *f, unsigned *s, void *dst, size_t size) {
    if (*f < 8) memcpy(dst, &c->v[(*f)++][0], size);
    else { memcpy(dst, stack_slot(c, *s), size); *s += 1; }
}
static inline void put_gp(jit_context *c, const void *src, size_t size) {
    if (size <= 16) { c->x[0] = 0; c->x[1] = 0; memcpy(&c->x[0], src, size); }
    else memcpy((void *)(uintptr_t)c->x[8], src, size);   /* large results: the caller's buffer in x8 */
}
static inline void put_fp(jit_context *c, const void *src, size_t size) {
    c->v[0][0] = 0; c->v[0][1] = 0; memcpy(&c->v[0][0], src, size);
}

'''


def generate(sources, include='nvn_protos.h', table='bridge_nvn_table'):
    seen, out, names = set(), [HEADER % {'include': include}], []
    for path in sources:
        for macro, name, ret, params in definitions(Path(path).read_text(encoding='utf-8', errors='replace')):
            if name in seen:
                continue
            seen.add(name)
            out.append(thunk(name, ret, params, 'bt_'))
            names.append(name)
    out.append(f'const bridge_entry {table}[] = {{\n')
    out += [f'    {{"{n}", bt_{n}}},\n' for n in sorted(names)]
    out.append('};\nconst unsigned %s_count = %d;\n' % (table.removesuffix('_table'), len(names)))
    return ''.join(out), len(names)


def main():
    import argparse
    a = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    a.add_argument('output')
    a.add_argument('sources', nargs='+')
    a.add_argument('--include', default='nvn_protos.h', help='header that declares the parameter types')
    a.add_argument('--table', default='bridge_nvn_table', help='name of the generated table')
    args = a.parse_args()
    text, n = generate(args.sources, args.include, args.table)
    sys.argv[1] = args.output
    Path(sys.argv[1]).write_text(text, newline='\n')
    print(f'{n} thunks')


if __name__ == '__main__':
    main()
