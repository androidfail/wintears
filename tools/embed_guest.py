"""Assemble an ARM64 .S file with llvm-mc and write a C header with its code bytes and symbol offsets.

Usage: python3 tools/embed_guest.py <in.S> <out.h>
The generated header is committed, so building the tests never needs an ARM64 assembler."""
import os
import subprocess
import sys
import tempfile


def main():
    src, out = sys.argv[1], sys.argv[2]
    with tempfile.TemporaryDirectory() as tmp:
        obj, raw = os.path.join(tmp, 'p.o'), os.path.join(tmp, 'p.bin')
        subprocess.run(['llvm-mc', '-triple=aarch64-none-elf', '-filetype=obj', src, '-o', obj], check=True)
        subprocess.run(['llvm-objcopy', '-O', 'binary', '--only-section=.text', obj, raw], check=True)
        code = open(raw, 'rb').read()
        syms = subprocess.run(['llvm-nm', '--defined-only', obj], check=True, capture_output=True, text=True).stdout
    offsets = sorted((int(v, 16), n) for v, t, n in (line.split() for line in syms.splitlines()) if t == 'T')
    lines = ['/* Generated by tools/embed_guest.py from %s. Do not edit. */' % os.path.basename(src), '#pragma once',
             '#include <stdint.h>', '', 'static const uint8_t guest_code[%d] = {' % len(code)]
    for i in range(0, len(code), 16):
        lines.append('    ' + ', '.join('0x%02x' % b for b in code[i:i + 16]) + ',')
    lines += ['};', '', 'enum {']
    lines += ['    GUEST_%s = 0x%x,' % (n.upper(), v) for v, n in offsets]
    lines += ['};', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))


if __name__ == '__main__':
    main()
