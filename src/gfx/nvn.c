/* Live texture by storage address. The game re-initialises transient textures (G-buffer etc.) every frame at the same
   pool memory without registering the texture-pool descriptor again (an NVN descriptor refers to the memory, so it stays
   valid on hardware). A registration whose serial has since been finalised is redirected by the replay to the texture
   living at that address now (nvn_tex_live_at). */
static nvn_hmap g_live_mem = {.klen = 8};   /* storage address -> malloc'd tex_t copy of the live texture */
static pthread_mutex_t g_live_mu = PTHREAD_MUTEX_INITIALIZER;
static void live_put(const tex_t *o) {
    if (!o->mem) return;
    uint64_t k = (uint64_t)(uintptr_t)o->mem; tex_t *c = malloc(sizeof *c); if (!c) die("live texture copy"); *c = *o;
    pthread_mutex_lock(&g_live_mu); tex_t *old = nvn_hm_put(&g_live_mem, &k, c); pthread_mutex_unlock(&g_live_mu); free(old);
}
static void live_del(const tex_t *o) {
    if (!o->mem) return;
    uint64_t k = (uint64_t)(uintptr_t)o->mem;
    pthread_mutex_lock(&g_live_mu);
    tex_t *cur = nvn_hm_get(&g_live_mem, &k);
    if (cur && cur->serial == o->serial) { nvn_hm_del(&g_live_mem, &k); free(cur); }
    pthread_mutex_unlock(&g_live_mu);
}
int nvn_tex_live_at(const void *mem, tex_t *out) {
    if (!mem) return 0;
    uint64_t k = (uint64_t)(uintptr_t)mem;
    pthread_mutex_lock(&g_live_mu); tex_t *cur = nvn_hm_get(&g_live_mem, &k); if (cur) *out = *cur; pthread_mutex_unlock(&g_live_mu);
    return cur != NULL;
}
