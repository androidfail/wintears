#define OLOG(...) do { if (g_log) LOG("[nvn] " __VA_ARGS__); } while (0)
static int g_log;   /* TOTK_NVN_LOG=1 logs object creation (upstream DM_NVN_LOG) */

/* ---------- registry and stubs ---------- */
extern const char *const nvn_names[];   /* main's NVN name table (upstream names.txt, generated by CMake) */
extern const unsigned nvn_name_count;

#define NVN_MAX_IMPL 640
static const nvn_impl *g_impl[NVN_MAX_IMPL];
static unsigned g_nimpl;
void nvn_register(const nvn_impl *e) {
    if (g_nimpl == NVN_MAX_IMPL) { fprintf(stderr, "too many NVN implementations\n"); abort(); }
    g_impl[g_nimpl++] = e;
}

/* Only change GPU state / only run on the GPU: the null device does nothing with them. TOTK: entries that would
   silently drop GPU work (indirect draws / dispatch, downsample, depth bounds test) are not here, so a real call
   stops. WaitSync / WaitEvent rely on in-order execution on the one queue. */
static const char *const g_nops[] = {
    "nvnCommandBufferSetPatchSize",
    "nvnCommandBufferWaitSync",
    "nvnCommandBufferSetShaderScratchMemory",
    "nvnCommandBufferWaitEvent",
    "nvnWindowFinalize",
};

static int name_known(const char *name) {
    for (unsigned i = 0; i < nvn_name_count; i++) if (!strcmp(nvn_names[i], name)) return 1;
    return 0;
}
static const nvn_impl *impl_of(const char *name) {
    for (unsigned i = 0; i < g_nimpl; i++) if (!strcmp(g_impl[i]->name, name)) return g_impl[i];
    return NULL;
}
static int nop_index(const char *name) {
    for (unsigned i = 0; i < sizeof g_nops / sizeof *g_nops; i++) if (!strcmp(g_nops[i], name)) return (int)i;
    return -1;
}

static void nvn_init(void) {
    static int done; if (done) return; done = 1;
    g_log = getenv("TOTK_NVN_LOG") != NULL;
    for (unsigned i = 0; i < g_nimpl; i++) {
        const nvn_impl *e = g_impl[i];
        if (!e->extra && !name_known(e->name)) die("NVN implementation %s is not in main's name table", e->name);
        if (!bridge_nvn_thunk(e->name)) die("NVN implementation %s has no bridge thunk (its signature must be upstream's)", e->name);
        for (unsigned j = 0; j < i; j++) if (!strcmp(g_impl[j]->name, e->name)) die("NVN %s implemented twice", e->name);
    }
    for (unsigned k = 0; k < sizeof g_nops / sizeof *g_nops; k++) {
        if (!name_known(g_nops[k])) die("NVN no-op %s is not in main's name table", g_nops[k]);
        if (impl_of(g_nops[k])) die("NVN %s both implemented and listed as a no-op", g_nops[k]);
    }
    unsigned sem = 0; for (unsigned i = 0; i < g_nimpl; i++) sem += !g_impl[i]->extra;
    gpu_init();
    LOG("NVN %s device: %u names, %u implemented (%u + %u no-ops), %u extra entry points; the rest stop when called",
        gpu_name(), nvn_name_count, sem + (unsigned)(sizeof g_nops / sizeof *g_nops), sem,
        (unsigned)(sizeof g_nops / sizeof *g_nops), g_nimpl - sem);
}

static void nop_thunk(jit_context *c, void *fn) { (void)c; (void)fn; }
static void unimpl_thunk(jit_context *c, void *name) {
    LOG("unimplemented NVN call %s (x0=%#llx x1=%#llx x2=%#llx)", (const char *)name,
        (unsigned long long)c->x[0], (unsigned long long)c->x[1], (unsigned long long)c->x[2]);
    host_report_guest(c);
    die("unimplemented NVN call %s", (const char *)name);
}

void *nvn_slot_fn(const char *name) {
    nvn_init();
    const nvn_impl *e = impl_of(name);
    if (!e) die("nvn_slot_fn: %s is not implemented", name);
    return e->fn;
}

static struct { const char *name; uint64_t stub; } g_stubs[1024];
static unsigned g_nstubs;
static pthread_mutex_t g_stub_mu = PTHREAD_MUTEX_INITIALIZER;
uint64_t nvn_stub(const char *name) {
    nvn_init();
    if (!name) return 0;
    pthread_mutex_lock(&g_stub_mu);
    for (unsigned i = 0; i < g_nstubs; i++) if (!strcmp(g_stubs[i].name, name)) { pthread_mutex_unlock(&g_stub_mu); return g_stubs[i].stub; }
    const nvn_impl *e = impl_of(name);
    const char *stable = e ? e->name : NULL;
    bridge_thunk thunk; void *fn;
    int nop = nop_index(name);
    if (e) { thunk = bridge_nvn_thunk(name); fn = e->fn; }
    else if (nop >= 0) { stable = g_nops[nop]; thunk = nop_thunk; fn = NULL; }
    else {
        for (unsigned i = 0; i < nvn_name_count && !stable; i++) if (!strcmp(nvn_names[i], name)) stable = nvn_names[i];
        if (!stable) {
            pthread_mutex_unlock(&g_stub_mu);
            LOG("NVN lookup of an unknown name: %s (NULL, as upstream)", name);
            return 0;
        }
        thunk = unimpl_thunk; fn = (void *)stable;
    }
    if (g_nstubs == sizeof g_stubs / sizeof *g_stubs) die("too many NVN stubs");
    uint64_t stub = bridge_add(host_bridge(), stable, thunk, fn);
    if (!stub) die("bridge stub page full");
    g_stubs[g_nstubs].name = stable; g_stubs[g_nstubs++].stub = stub;
    pthread_mutex_unlock(&g_stub_mu);
    OLOG("lookup %s -> %#llx%s", name, (unsigned long long)stub, e || nop >= 0 ? "" : " (stops when called)");
    return stub;
}

