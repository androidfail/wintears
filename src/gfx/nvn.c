/* The NVN layer: the game's NVN calls, implemented on the host. Port of upstream
   third_party/d2r_gfx/gfx/nvn/hle_nvn.c (TOTK paths; Breath of the Wild branches, Mac diagnostics, the translation
   thread and the timing instrumentation left out). Function names, object layouts (nvn_obj.h, used unchanged) and
   command records are upstream's, so upstream fixes merge by hand.

   nvnBootstrapLoader is taken over, so the NVN driver inside sdk never runs. Every name main asks for gets a bridge
   stub (nvn_stub):
     - names with semantics (device / memory pools / textures and samplers / queue / window / sync / events / command
       buffer memory) are implemented per NVN semantics, and the objects are real, in the game's object memory;
     - commands that only change GPU state (state objects, bindings, draws, clears...) are recorded and handed to the
       GPU backend at submit (nvn_backend.h; nvn_null.c draws nothing);
     - the rest stop the run with their name when called.
   GPU address = CPU address: memory pools are the game's own memory. */
