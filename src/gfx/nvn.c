static void bind_handles(NVNcommandBuffer *c, int op, int st, int first, int n, const uint64_t *h) { bind_handles_rec(c, op, st, first, n, h, 0); }
/* NVN 55 *Deferred binds (nvn_ext.c): the original driver (sdk+0x46cc00 BindTexturesDeferred) only writes a control
   token and the pointer to the game's handle array; the handles are read when the command buffer is submitted. The
   game relies on that: material command buffers are recorded first and their handle tables filled before the submit
   (reading them at record time made objects flicker on the Mac, 2026-10-15). hw_bytes: command bytes reported for the
   plain variant (resource heaps are sized from them). */
void nvn_bind_handles_deferred(NVNcommandBuffer *c, int op, int st, int first, int n, const uint64_t *h, size_t hw_bytes) {
    bind_handles_rec(c, op, st, first, n, h, 1);
    if (hw_bytes && n >= 0 && n <= 32) hw_fix(CB(c), hw_bytes);
}
static int g_def_on = -1;   /* TOTK_DEFERRED_BINDS=0: keep the record-time handles */
static void resolve_deferred(const uint8_t *p, int depth) {   /* read the handles of every deferred bind in a submitted recording */
    for (;;) {
        op_hdr h; memcpy(&h, p, sizeof h);
        if (h.size < 8 || (h.size & 7) || h.op >= OP_COUNT_) die("corrupt recording at %p while resolving deferred binds (op %u size %u)", (const void *)p, h.op, h.size);
        if (h.op == OP_END) return;
        if (h.op == OP_JUMP) { memcpy(&p, p + 8, 8); continue; }
        if (h.op == OP_CALL) {
            uint64_t t; memcpy(&t, p + 8, 8);
            if (depth >= 16) die("deferred bind resolution: call depth over 16");
            resolve_deferred((const uint8_t *)(uintptr_t)t, depth + 1);
        } else if (h.op == OP_BIND_TEX || h.op == OP_BIND_IMG || h.op == OP_BIND_SAMP) {
            p_bind_handles *b = (p_bind_handles *)(uintptr_t)(p + 8);
            if (b->src && b->n > 0 && b->n <= 32) memcpy(b->h, (const void *)(uintptr_t)b->src, 8 * (size_t)b->n);
        }
        p += h.size;
    }
}
